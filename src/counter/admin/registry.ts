/**
 * Map a BCP-47 tag to the registry's language key.
 *
 * Chinese is split by script, not region: zh-TW, zh-HK and zh-Hant all read
 * Traditional characters.
 */
export function registryLanguage(tag: string | undefined): RegistryLanguage | null {
  const lower = (tag ?? "").toLowerCase();
  const base = lower.split("-")[0];
  if (base === "zh") {
    return /-(tw|hk|mo|hant)\b/.test(lower) ? "zh-Hant" : "zh-Hans";
  }
  const supported: RegistryLanguage[] = ["ko", "en", "vi", "id", "ru", "th", "mn", "uz"];
  return (supported as string[]).includes(base) ? (base as RegistryLanguage) : null;
}

